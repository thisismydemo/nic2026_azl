function New-NIC26TerraformBackendConfig {
    <#
    .SYNOPSIS
        Generates <solution>\terraform\backend.generated.hcl (the -backend-config file) from terraform_backend in the environment file.
    .DESCRIPTION
        Every Terraform root declares an empty 'backend "azurerm" {}'; the state location is a deployment value, so it lives in the
        shared environment file under terraform_backend (subscription_id, resource_group_name, storage_account_name,
        container_name, use_azuread_auth and the optional key_prefix). This function renders those values plus the state key
        <key_prefix>/<solution name>.tfstate (just <solution name>.tfstate without a prefix) as a backend-config file for
        'terraform init -backend-config=<file>'. It contains names and IDs only, never a key or token (authentication is the
        operator's own Entra sign-in). Without -Execute the HCL text is returned; with -Execute the file is written
        (UTF-8, LF) and its FileInfo returned; -WhatIf is honoured.
    .PARAMETER Solution
        Solution folder, solution.yml path, or solution name (searched under automation\).
    .PARAMETER Config
        Object returned by Get-NIC26Config (its 'values' are used) or a dictionary of canonical values.
    .PARAMETER OutFile
        Override the output path (default <solution>\terraform\backend.generated.hcl).
    .PARAMETER Execute
        Write the file. Default is preview only.
    .EXAMPLE
        $cfg = Get-NIC26Config -Scope azure-local
        New-NIC26TerraformBackendConfig -Solution cluster-deploy -Config $cfg -Execute
    .OUTPUTS
        System.String (preview) or System.IO.FileInfo (with -Execute)
    #>
    [Diagnostics.CodeAnalysis.SuppressMessageAttribute('PSUseShouldProcessForStateChangingFunctions', '', Justification = 'ShouldProcess is implemented through SupportsShouldProcess and checked before the file is written.')]
    [CmdletBinding(SupportsShouldProcess)]
    [OutputType([string], [System.IO.FileInfo])]
    param(
        [Parameter(Mandatory, Position = 0)]
        [ValidateNotNullOrEmpty()]
        [string]$Solution,

        [Parameter(Mandatory, Position = 1)]
        [AllowNull()]
        [object]$Config,

        [Parameter()]
        [string]$OutFile,

        [Parameter()]
        [switch]$Execute
    )

    $root = Resolve-NIC26SolutionPath -Solution $Solution
    $manifest = Get-NIC26SolutionManifest -Path $root
    $values = ConvertTo-NIC26ConfigValues -Config $Config
    if (-not $values.Contains('terraform_backend') -or $values['terraform_backend'] -isnot [System.Collections.IDictionary]) {
        throw "The environment file has no terraform_backend block (subscription_id, resource_group_name, storage_account_name, container_name); it is required to generate the Terraform backend configuration for '$($manifest['name'])'."
    }
    $backend = $values['terraform_backend']
    $missing = @('subscription_id', 'resource_group_name', 'storage_account_name', 'container_name') | Where-Object { -not $backend.Contains($_) -or [string]::IsNullOrWhiteSpace([string]$backend[$_]) }
    if ($missing) { throw "terraform_backend is missing: $($missing -join ', ')." }

    $prefix = if ($backend.Contains('key_prefix') -and -not [string]::IsNullOrWhiteSpace([string]$backend['key_prefix'])) { ([string]$backend['key_prefix']).Trim('/') + '/' } else { '' }
    $useAzureAd = if ($backend.Contains('use_azuread_auth')) { [bool]$backend['use_azuread_auth'] } else { $true }
    $lines = @(
        "# Generated by NIC26.Automation New-NIC26TerraformBackendConfig for '$($manifest['name'])' from terraform_backend in the environment file. Do not edit; do not commit."
        "subscription_id      = `"$($backend['subscription_id'])`""
        "resource_group_name  = `"$($backend['resource_group_name'])`""
        "storage_account_name = `"$($backend['storage_account_name'])`""
        "container_name       = `"$($backend['container_name'])`""
        "key                  = `"$prefix$($manifest['name']).tfstate`""
        "use_azuread_auth     = $($useAzureAd.ToString().ToLowerInvariant())"
    )
    $content = ($lines -join "`n") + "`n"

    if (-not $OutFile) {
        $OutFile = Join-Path $root 'terraform' 'backend.generated.hcl'
    }
    if (-not $Execute) {
        Write-NIC26Log -Message "Preview only for '$($manifest['name'])' (pass -Execute to write $OutFile)" -Level Verbose
        return $content
    }
    if ($PSCmdlet.ShouldProcess($OutFile, 'Write generated Terraform backend configuration')) {
        return Write-NIC26GeneratedFile -Path $OutFile -Content $content
    }
}
